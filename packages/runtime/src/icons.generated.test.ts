import { describe, expect, it } from "vitest";
import { loadIconTable, renderIconTable } from "../scripts/gen-icons.ts";
import { decodeIconNodes, encodeIconNodes } from "./icon-codec";
import { LUCIDE_ICON_SET } from "./icons.generated";

describe("icons.generated", () => {
  it("records the lucide set metadata", () => {
    expect(LUCIDE_ICON_SET.name).toBe("lucide");
    expect(LUCIDE_ICON_SET.kind).toBe("stroke");
    expect(LUCIDE_ICON_SET.viewBox).toBe("0 0 24 24");
    expect(LUCIDE_ICON_SET.defaultStrokeWidth).toBe(2);
  });

  it("matches a fresh generation from the lucide-static source", () => {
    const fresh = loadIconTable();
    const freshIcons: Record<string, string> = {};
    for (const entry of Object.entries(fresh.icons).sort(([a], [b]) =>
      a < b ? -1 : a > b ? 1 : 0,
    )) {
      freshIcons[entry[0]] = encodeIconNodes(entry[1]);
    }
    expect(Object.keys(LUCIDE_ICON_SET.icons)).toEqual(Object.keys(freshIcons));
    expect(LUCIDE_ICON_SET.icons).toEqual(freshIcons);
    expect(LUCIDE_ICON_SET.aliases).toEqual(fresh.aliases);
    const rendered = renderIconTable(fresh);
    expect(rendered).toContain(
      "// @generated by packages/runtime/scripts/gen-icons.ts",
    );
    expect(rendered.split("\n").length).toBeGreaterThan(2000);
  });

  it("covers the full canonical lucide set plus aliases", () => {
    const icons = Object.keys(LUCIDE_ICON_SET.icons);
    const aliases = Object.keys(LUCIDE_ICON_SET.aliases);
    expect(icons.length).toBe(1924);
    expect(aliases.length).toBe(269);
    expect(icons).toEqual([...icons].sort());
    expect(aliases).toEqual([...aliases].sort());
    for (const [alias, canonical] of Object.entries(LUCIDE_ICON_SET.aliases)) {
      expect(LUCIDE_ICON_SET.icons[canonical]).toBeDefined();
      expect(LUCIDE_ICON_SET.icons[alias]).toBeUndefined();
    }
  });

  it("decodes every icon entry into svg nodes", () => {
    let nodeCount = 0;
    let encodedSize = 0;
    for (const [name, encoded] of Object.entries(LUCIDE_ICON_SET.icons)) {
      const nodes = decodeIconNodes(encoded);
      expect(nodes.length).toBeGreaterThan(0);
      nodeCount += nodes.length;
      encodedSize += name.length + encoded.length;
      for (const node of nodes) {
        expect(Object.keys(node.attrs).length).toBeGreaterThan(0);
      }
    }
    expect(nodeCount).toBeGreaterThan(7000);
    expect(encodedSize).toBeLessThan(400_000);
  });
});
