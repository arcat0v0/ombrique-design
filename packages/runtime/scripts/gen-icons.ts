import { createRequire } from "node:module";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
  encodeIconNodes,
  isIconTag,
  type IconNode,
} from "../src/icon-codec.ts";

const here = dirname(fileURLToPath(import.meta.url));
const TARGET = join(here, "..", "src", "icons.generated.ts");

export interface IconTableData {
  source: string;
  kind: "stroke" | "fill";
  viewBox: string;
  defaultStrokeWidth: number;
  icons: Record<string, IconNode[]>;
  aliases: Record<string, string>;
}

function normalizeNode(node: unknown): IconNode | null {
  if (!Array.isArray(node) || node.length !== 2) return null;
  const tag = node[0];
  if (typeof tag !== "string" || !isIconTag(tag)) return null;
  const attrs: Record<string, string> = {};
  const rawAttrs = node[1];
  if (rawAttrs && typeof rawAttrs === "object") {
    for (const [key, value] of Object.entries(
      rawAttrs as Record<string, unknown>,
    )) {
      attrs[key] =
        key === "points" ? String(value).replaceAll(",", " ") : String(value);
    }
  }
  return { tag, attrs };
}

export function loadIconTable(): IconTableData {
  const root = dirname(
    createRequire(import.meta.url).resolve("lucide-static/package.json"),
  );
  const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8")) as {
    version?: unknown;
  };
  const version = pkg.version;
  if (typeof version !== "string") {
    throw new Error("lucide-static package.json has no version");
  }
  const rawIcons = JSON.parse(
    readFileSync(join(root, "icon-nodes.json"), "utf8"),
  ) as Record<string, unknown> | null;
  const icons: Record<string, IconNode[]> = {};
  for (const [name, raw] of Object.entries(rawIcons ?? {})) {
    icons[name] = (Array.isArray(raw) ? raw : [])
      .map(normalizeNode)
      .filter((node): node is IconNode => node !== null);
  }

  const canonical = new Set(Object.keys(icons));
  const groups = new Map<string, string[]>();
  for (const file of readdirSync(join(root, "icons")).filter((f) =>
    f.endsWith(".svg"),
  )) {
    const svg = readFileSync(join(root, "icons", file), "utf8");
    const openEnd = svg.indexOf(">", svg.indexOf("<svg"));
    const closeStart = svg.lastIndexOf("</svg>");
    const body =
      openEnd > 0 && closeStart > openEnd
        ? svg.slice(openEnd + 1, closeStart).replace(/\s+/g, " ")
        : "";
    const names = groups.get(body) ?? [];
    names.push(file.slice(0, -4));
    groups.set(body, names);
  }

  const aliases: Record<string, string> = {};
  for (const [body, names] of groups) {
    const canonicalNames = names.filter((name) => canonical.has(name));
    for (const name of names) {
      if (canonical.has(name)) continue;
      const canonicalName = canonicalNames[0];
      if (canonicalNames.length !== 1 || canonicalName === undefined) {
        throw new Error(`alias ${name} cannot be resolved for body ${body}`);
      }
      aliases[name] = canonicalName;
    }
  }

  return {
    source: `lucide-static@${version}`,
    kind: "stroke",
    viewBox: "0 0 24 24",
    defaultStrokeWidth: 2,
    icons,
    aliases,
  };
}

export function renderIconTable(data: IconTableData): string {
  const iconLines = Object.entries(data.icons)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(
      ([name, nodes]) =>
        `    ${JSON.stringify(name)}: ${JSON.stringify(encodeIconNodes(nodes))},`,
    );
  const aliasLines = Object.entries(data.aliases)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(
      ([name, target]) =>
        `    ${JSON.stringify(name)}: ${JSON.stringify(target)},`,
    );
  return [
    "// biome-ignore-all format: generated by scripts/gen-icons.ts",
    "// @generated by packages/runtime/scripts/gen-icons.ts",
    `// Source: ${data.source}. Do not edit by hand.`,
    "",
    'import type { IconSetDefinition } from "./icon-codec";',
    "",
    "export const LUCIDE_ICON_SET: IconSetDefinition = {",
    '  name: "lucide",',
    `  kind: ${JSON.stringify(data.kind)},`,
    `  viewBox: ${JSON.stringify(data.viewBox)},`,
    `  defaultStrokeWidth: ${data.defaultStrokeWidth},`,
    "  icons: {",
    ...iconLines,
    "  },",
    "  aliases: {",
    ...aliasLines,
    "  },",
    "};",
    "",
  ].join("\n");
}

function main(): void {
  const rendered = renderIconTable(loadIconTable());
  if (existsSync(TARGET) && readFileSync(TARGET, "utf8") === rendered) {
    console.log("icons.generated.ts is up to date");
    return;
  }
  writeFileSync(TARGET, rendered, "utf8");
  console.log("rewrote icons.generated.ts");
}

const entry = process.argv[1];
if (entry && pathToFileURL(entry).href === import.meta.url) main();
